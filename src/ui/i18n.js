  const STORE = 'csdemo.lang';
  let lang = 'pt';
  try {
    const saved = localStorage.getItem(STORE);
    if (saved && T[saved]) lang = saved;
    else {
      const nav = (navigator.language || 'pt').slice(0, 2).toLowerCase();
      lang = T[nav] ? nav : 'pt';
    }
  } catch (e) { /* no localStorage */ }

  function tr(key, vars) {
    const dict = T[lang] || T.pt;
    let s = key.split('.').reduce((o, k) => (o ? o[k] : undefined), dict);
    if (s == null) s = key.split('.').reduce((o, k) => (o ? o[k] : undefined), T.pt);
    if (s == null) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    return s;
  }

  /** Translates a message stored as {key, vars} (warnings, errors). */
  function trMsg(m) {
    if (!m) return '';
    if (typeof m === 'string') return m;
    return tr(m.key, m.vars) + (m.hint ? ' ' + tr(m.hint) : '');
  }

  /** Error carrying a translation key (text is built when shown). */
  function i18nError(key, vars, hint) {
    const e = new Error(tr(key, vars));
    e.i18n = { key, vars, hint };
    return e;
  }

  function applyI18n(rootEl) {
    const r = rootEl || document;
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;
    for (const el of r.querySelectorAll('[data-i18n]')) el.textContent = tr(el.dataset.i18n);
    for (const el of r.querySelectorAll('[data-i18n-html]')) el.innerHTML = tr(el.dataset.i18nHtml);
    for (const el of r.querySelectorAll('[data-i18n-title]')) el.title = tr(el.dataset.i18nTitle);
    for (const el of r.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', tr(el.dataset.i18nAria));
  }

  function setLang(l) {
    if (!T[l]) return;
    lang = l;
    try { localStorage.setItem(STORE, l); } catch (e) { /* ignora */ }
    applyI18n();
  }

